const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:390,height:844}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  try{
    await page.goto('file://'+process.cwd()+'/index.html');
    const checks=await page.evaluate(async()=>{
      const checks=[],check=(name,ok)=>{checks.push({name,pass:!!ok});if(!ok)throw Error('FAIL: '+name)};
      newCampaign();['volt','wisp','bulwark','lynx'].forEach(recruitQuick);
      S.guide=null;S.tut={dq:[],skip:true};S.tutDone=true;
      const volt=S.heroes.find(h=>h.cls==='volt'),wisp=S.heroes.find(h=>h.cls==='wisp');
      volt.gear.arms='baton';volt.gear.acc='uplink';volt.pouch.push('c_smoke');
      S.inv={v:S.villains[0].key,clues:2};
      startShowdown();const sd=S.sd;
      sd.intro=false;sd.busy=false;sd.quality='normal';
      sd.sel=0;sd.mode=null;sd.civs=[];sd.hench=[];sd.bombs=[];sd.beams=[];
      const u=sd.units[0],wu=sd.units[1];u.x=4;u.y=4;wu.x=1;wu.y=7;
      render();
      const menus=[...document.querySelectorAll('.combat-dropdown')];
      check('Exactly two dropdowns present',menus.length===2);
      check('Abilities precedes Other Actions',menus[0].classList.contains('abilities-dropdown')&&menus[1].classList.contains('other-actions'));
      check('Move button displays a movement icon',!!document.querySelector('[data-a="mode:move"] svg'));
      check('Attack button displays an action icon',!!document.querySelector('[data-a="mode:attack"] svg'));
      const summary=document.querySelector('.abilities-dropdown .combat-menu-toggle');
      summary.click();
      check('Ability menu opens on click',document.querySelector('.abilities-dropdown .combat-menu-toggle').getAttribute('aria-expanded')==='true');
      check('Primary power is listed',!!document.querySelector('[data-a="combatPick:ability:power"]'));
      check('Equipped Baton power is listed',!!document.querySelector('[data-a="combatPick:ability:baton"]'));
      check('Equipped Orbital Strike is listed',!!document.querySelector('[data-a="combatPick:ability:uplink"]'));
      check('Pouch consumable is listed',!!document.querySelector('[data-a="combatPick:ability:c_smoke"]'));
      check('Primary Arc Burst icon shows Action',document.querySelector('[data-a="combatPick:ability:power"] .combat-cost-icon').getAttribute('aria-label')==='Uses action');
      check('Orbital Strike icon shows Action',document.querySelector('[data-a="combatPick:ability:uplink"] .combat-cost-icon').getAttribute('aria-label')==='Uses action');
      check('Equipment Stun Charge icon shows Free',document.querySelector('[data-a="combatPick:ability:baton"] .combat-cost-icon').getAttribute('aria-label')==='Free action');
      check('Consumable icon shows Free',document.querySelector('[data-a="combatPick:ability:c_smoke"] .combat-cost-icon').getAttribute('aria-label')==='Free action');
      const beforePower=u.res.tech, beforeStr=u.buffStr, beforeAct=u.acted;
      document.querySelector('[data-a="combatPick:ability:baton"]').click();
      check('Equipment selection records choice',sd.combatPick&&sd.combatPick.key==='baton');
      check('Equipment selection spends nothing',u.res.tech===beforePower&&u.buffStr===beforeStr&&u.acted===beforeAct&&sd.mode===null);
      check('Equipment details appear underneath controls',document.querySelector('.combat-choice').textContent.includes('Stun Charge')&&document.querySelector('.combat-choice').textContent.includes('From Shock Baton'));
      check('Menu closes after selection without activating',document.querySelector('.abilities-dropdown .combat-menu-toggle').getAttribute('aria-expanded')==='false');
      document.querySelector('[data-a="combatClear"]').click();
      check('Cancel selection does not activate',!sd.combatPick&&u.res.tech===beforePower&&u.buffStr===beforeStr);
      document.querySelector('[data-a="combatPick:ability:baton"]').click();
      document.querySelector('[data-a="combatUse"]').click();
      await new Promise(resolve=>setTimeout(resolve,900));
      check('Confirm activates Stun Charge',u.buffStr===beforeStr+3&&u.res.tech===beforePower-2&&!u.acted);
      u.res.tech=pwrMax(volt);
      document.querySelector('[data-a="combatPick:ability:power"]').click();
      const saved=u.res.tech;
      check('Targeted primary selection enters targeting without spending',sd.mode==='arc'&&u.res.tech===saved&&!u.acted);
      check('Primary details show Arc Burst',document.querySelector('.combat-choice').textContent.includes('Arc Burst'));
      check('Targeted primary has no activate button',!document.querySelector('.combat-choice [data-a="combatUse"]'));
      check('Targeted primary says to click the board',document.querySelector('.combat-board-prompt')?.textContent.includes('Click the board to activate'));
      document.querySelector('[data-a="combatPick:other:avoidDamage"]').click();
      check('Other Actions selection does not trigger ability or consume action',!u.acted&&!u.avoidDamage&&sd.mode===null);
      check('Other Action description appears below',document.querySelector('.combat-choice').textContent.includes('+5'));
      check('Avoid Damage shows Action icon',document.querySelector('[data-a="combatPick:other:avoidDamage"] .combat-cost-icon').getAttribute('aria-label')==='Uses action');
      check('Rally Spirit shows Action icon',document.querySelector('[data-a="combatPick:other:rallySpirit"] .combat-cost-icon').getAttribute('aria-label')==='Uses action');
      u.freeEvac=true;render();
      check('Free escort shows Lightning icon',document.querySelector('[data-a="combatPick:other:escort"] .combat-cost-icon').getAttribute('aria-label')==='Free action');
      document.querySelector('[data-a="combatPick:other:rallySpirit"]').click();
      check('Rally selection enters targeting without using the action',sd.mode==='rallySpirit'&&!u.acted);
      check('Rally has no Use action button',!document.querySelector('.combat-choice [data-a="combatUse"]'));
      sd.mode=null;sd.sel=1;render();
      check('Other hero selection does not show old choice',!document.querySelector('.combat-choice'));
      document.querySelector('[data-a="combatPick:ability:power"]').click();
      check('Magic primary Blur is shown',document.querySelector('.combat-choice').textContent.includes('Blur'));
      check('Magic primary is Free action',document.querySelector('[data-a="combatPick:ability:power"] .combat-cost-icon').getAttribute('aria-label')==='Free action');
      const oldArc=wu.res.magic,oldEva=wu.buffEva||0;
      check('Selecting Blur leaves magic and Evasion untouched',wu.res.magic===oldArc&&(wu.buffEva||0)===oldEva);
      document.querySelector('[data-a="combatUse"]').click();
      await new Promise(resolve=>setTimeout(resolve,850));
      check('Confirm executes free Blur without using action',wu.res.magic===oldArc-1&&wu.buffEva===oldEva+2&&!wu.acted);
      const tutorialStep=TUT.findIndex(b=>b.id==='b-stun'),priorTut=S.tut;
      S.tut={b:tutorialStep,dq:[]};
      check('Tutorial allows opening Abilities',!tutBlock('combatMenu:abilities'));
      check('Tutorial allows selecting Stun Charge',!tutBlock('combatPick:ability:baton'));
      check('Tutorial allows confirming Stun Charge',!tutBlock('combatUse'));
      S.tut=priorTut;
      return checks;
    });
    console.log(JSON.stringify(checks,null,2));
    // Real pointer interactions catch overlays/scroll problems that DOM .click() misses.
    // Start the pointer regression from a known closed state. Earlier DOM
    // checks may leave a dropdown open; clicking an open toggle closes it.
    await page.evaluate(()=>{ S.sd.combatMenuOpen=null; render(); });
    assert.equal(await page.locator('.abilities-dropdown .combat-menu-toggle').getAttribute('aria-expanded'),'false','Ability menu starts closed');
    await page.locator('.abilities-dropdown .combat-menu-toggle').click();
    assert.equal(await page.locator('.abilities-dropdown .combat-menu-toggle').getAttribute('aria-expanded'),'true','Pointer opens Abilities');
    await page.evaluate(()=>render());
    assert.ok(await page.locator('.abilities-dropdown .combat-menu-toggle').evaluate(el=>el.getAttribute('aria-expanded')==='true'),'Ability menu should remain open after an animation render');
    await page.locator('.abilities-menu [data-a="combatPick:ability:power"]').click();
    assert.ok(await page.locator('.combat-choice').textContent().then(t=>t.includes('Blur')),'Mobile: ability menu must be usable by pointer');
    await page.setViewportSize({width:1280,height:800});
    await page.locator('.other-actions .combat-menu-toggle').click();
    await page.locator('.other-actions-menu [data-a="combatPick:other:rallySpirit"]').click();
    assert.ok(await page.locator('.combat-choice').textContent().then(t=>t.includes('Rally Spirit')),'Desktop: other actions menu must be usable by pointer');
    console.log('Mobile and desktop pointer dropdown smoke tests passed.');
    assert.equal(errors.length,0,'Browser errors: '+errors.join('; '));
  }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
