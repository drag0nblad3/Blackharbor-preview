const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:390,height:844}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  try{
    await page.goto('file://'+process.cwd()+'/index.html');
    const setup=await page.evaluate(()=>{
      newCampaign();recruitQuick(Object.keys(HERO_BASE)[0]);recruitQuick(Object.keys(HERO_BASE)[1]);
      S.tut={dq:[],skip:true};S.tutDone=true;
      S.inv={v:S.villains[0].key,clues:2};
      startShowdown();const sd=S.sd;
      sd.intro=false;sd.busy=false;sd.quality='normal';sd.sel=0;sd.mode=null;
      sd.obs=[];sd.walls=[];sd.pits=[];sd.haz=[];sd.bombs=[];sd.beams=[];sd.hench=[];sd.civs=[];sd.term=null;
      const u=sd.units[0],other=sd.units[1];u.x=4;u.y=4;other.x=0;other.y=8;
      sd.v.x=6;sd.v.y=4;sd.v.shape='one';delete sd.v.body;delete sd.v.sw;
      render();
      return {button:!!document.querySelector('.other-actions-menu [data-a="combatPick:other:avoidDamage"]')};
    });
    assert.ok(setup.button,'Avoid Damage button must appear in menu');
    await page.locator('details.other-actions summary').click();
    await page.locator('.other-actions-menu [data-a="combatPick:other:avoidDamage"]').click();
    assert.ok(await page.locator('.combat-choice').textContent().then(x=>x.includes('+3 Evasion')),'Selecting Avoid Damage must show a description');
    assert.ok(await page.evaluate(()=>!S.sd.units[0].acted&&!S.sd.units[0].avoidDamage),'Selection must not execute Avoid Damage');
    await page.locator('.combat-choice [data-a="combatUse"]').click();
    await page.waitForFunction(()=>!S.sd.busy);
    const checks=await page.evaluate(async()=>{
      const done=[];
      const check=(name,condition)=>{done.push({name,pass:!!condition});if(!condition)throw new Error('FAIL '+name)};
      const sd=S.sd,u=sd.units[0],other=sd.units[1],h=heroOf(u),oh=heroOf(other),baseHp=h.hp;
      check('Avoid Damage spends the action',u.acted&&u.avoidDamage);
      check('No cover grants exactly +3 evasion',avoidEva(u)===3);
      check('Repeat use blocked',document.querySelector('[data-a="combatPick:other:avoidDamage"]')!==null&&u.acted);
      check('Buff shown in hero UI',document.querySelector('.brest').textContent.includes('Avoid Damage +3'));
      sd.obs=['5,4'];
      check('Adjacent rubble grants +5 evasion',avoidEva(u)===5);
      check('Rubble recognized as valid cover',avoidCover(u).some(c=>c.kind==='rubble'));
      S.tut.dq=[1];await vHit(u,2,'Test Bolt','bolt');
      check('Ranged miss redirected into rubble',!sd.obs.includes('5,4')&&h.hp===baseHp);
      sd.walls=[{k:'5,4',perm:1,ttl:99}];
      S.tut.dq=[20];await vHit(u,2,'Test Bolt','bolt');
      check('Natural 20 hits even with +5 Evasion',h.hp===baseHp-2&&sd.walls.length===1);
      sd.walls=[];other.x=5;other.y=4;
      const hpOther=oh.hp;S.tut.dq=[1];await vHit(u,2,'Test Bolt','bolt');
      check('Miss can hit adjacent ally in attack path',oh.hp===hpOther-2);
      other.x=0;other.y=8;
      sd.civs=[{id:'test-civ',x:5,y:4}];const harm=sd.harmed;
      S.tut.dq=[1];await vHit(u,2,'Test Bolt','bolt');
      check('Miss can hit civilian cover',sd.harmed===harm+1&&sd.civs.length===0);
      sd.term={k:'5,4'};
      S.tut.dq=[1];await vHit(u,2,'Test Bolt','bolt');
      check('Miss destroys terminal cover',sd.term===null);
      sd.haz=[{k:'5,4',dmg:2,ttl:2,n:'fire'}];
      check('Hazardous tile does not count as cover',avoidEva(u)===3);
      sd.haz=[];sd.obs=['4,5'];
      const hpBefore=h.hp;S.tut.dq=[1];await vHit(u,2,'Test Bolt','bolt');
      check('Off-path cover gives +5 but cannot redirect',sd.obs.includes('4,5')&&h.hp===hpBefore);
      sd.obs=['5,4'];sd.v.x=0;sd.v.y=0;
      const hm={id:'test-hench',owner:sd.vkey,x:6,y:4,hp:2};
      sd.hench=[hm];const def=VILLAINS[sd.vkey].hench,oldRange=def.rng;
      def.rng=3;S.tut.dq=[1];await henchAct(hm);def.rng=oldRange;
      check('Henchman miss redirects into rubble',!sd.obs.includes('5,4')&&h.hp===hpBefore);
      sd.hench=[];sd.obs=[];sd.v.skip=true;
      await villainPhase();
      check('Avoid Damage expires after villain turn',!u.avoidDamage);
      check('Action becomes available next round',!u.acted);
      return done;
    });
    console.log(JSON.stringify(checks,null,2));
    assert.equal(errors.length,0,'Browser errors: '+errors.join('; '));
  }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
